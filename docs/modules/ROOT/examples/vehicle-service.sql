-- The tables of the vehicle service, as tib generate entity --ddl reads them.
CREATE TABLE depots (
  id UUID PRIMARY KEY,
  code VARCHAR(8) NOT NULL UNIQUE,
  opened_on DATE
);

CREATE TABLE vehicles (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  plate_number VARCHAR(16) NOT NULL UNIQUE,
  capacity INTEGER,
  price NUMERIC(12, 2),
  depot_id UUID,
  created_at TIMESTAMP WITH TIME ZONE NOT NULL,
  updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
  CONSTRAINT vehicles_depot_fk FOREIGN KEY (depot_id) REFERENCES depots (id)
);

CREATE INDEX vehicles_depot_idx ON vehicles (depot_id);
