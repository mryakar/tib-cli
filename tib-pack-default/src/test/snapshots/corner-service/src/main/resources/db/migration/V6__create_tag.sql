-- Written by tib when the entity was created. A change of the schema is a new migration.
CREATE TABLE TAG (
  ID BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  LABEL VARCHAR(255),
  BRANCH_ID BIGINT NOT NULL REFERENCES BRANCH (ID),
  OTHER_ID BIGINT REFERENCES BRANCH (ID)
);

CREATE INDEX TAG_BRANCH_ID_IDX ON TAG (BRANCH_ID);
CREATE INDEX TAG_OTHER_ID_IDX ON TAG (OTHER_ID);
