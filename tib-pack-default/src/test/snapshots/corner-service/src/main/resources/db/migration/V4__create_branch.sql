CREATE SEQUENCE BRANCH_SEQ START WITH 1 INCREMENT BY 50;

CREATE TABLE BRANCH (
  ID BIGINT PRIMARY KEY,
  CODE VARCHAR(255) NOT NULL,
  COUNT BIGINT,
  OPEN BOOLEAN,
  OPENED_AT TIMESTAMP,
  SEEN_AT TIMESTAMP WITH TIME ZONE,
  TOKEN UUID,
  RATIO NUMERIC,
  AMOUNT NUMERIC(10, 0),
  PARENT_ID BIGINT UNIQUE REFERENCES BRANCH (ID)
);
