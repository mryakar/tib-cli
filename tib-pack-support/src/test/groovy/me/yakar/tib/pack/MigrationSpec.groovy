package me.yakar.tib.pack

import java.nio.file.Files
import java.nio.file.Path
import me.yakar.tib.tree.Change
import me.yakar.tib.tree.Owner
import me.yakar.tib.tree.Tree
import spock.lang.Specification
import spock.lang.TempDir

class MigrationSpec extends Specification {

  @TempDir
  Path dir

  def "the migration of a new table comes after the migrations there: #existing"() {
    given:
    existing.each { writeMigration(it) }

    expect:
    Migration.path(Tree.at(dir), a()) == "${Migration.DIRECTORY}/${migration}"

    where:
    existing                                       | migration
    []                                             | 'V1__create_a.sql'
    ['V3__by_hand.sql', 'R__views.sql']            | 'V4__create_a.sql'
    ['V202611011200__by_hand.sql']                 | 'V202611011201__create_a.sql'
    ['V2.1__by_hand.sql']                          | 'V3__create_a.sql'
    ['V2_1_3__by_hand.sql', 'V1__by_hand.sql']     | 'V3__create_a.sql'
    ['V1__by_hand.sql', 'older/V5__by_hand.sql']   | 'V6__create_a.sql'
    ['notes.txt']                                  | 'V1__create_a.sql'
  }

  def "the migration of a table that has one is not written again"() {
    given:
    writeMigration('V2__create_a.sql')
    Tree tree = Tree.at(dir)

    when:
    Migration.write(tree, a())

    then:
    tree.changes() == []
  }

  def "the migration of a table that tib wrote before is not written again, also when it is #how"() {
    given:
    onDisk.each { writeMigration(it) }
    Tree tree = Tree.at(dir)
    tree.writtenBefore(['V0__create_b.sql', 'V1__create_a.sql'].collect {
      "${Migration.DIRECTORY}/${it}".toString()
    })

    when:
    Migration.write(tree, a())

    then:
    tree.changes() == []

    where:
    how       | onDisk
    'gone'    | ['V2__x.sql']
    'renamed' | ['V1__a.sql']
  }

  def "a new migration lasts, and is the developer's, with the header that says so"() {
    given:
    Tree tree = Tree.at(dir)

    when:
    Migration.write(tree, a())
    Change change = tree.changes()[0]

    then:
    tree.changes()*.path() == ["${Migration.DIRECTORY}/V1__create_a.sql".toString()]
    change.owner() == Owner.DEVELOPER
    new String(change.after(), 'UTF-8') == '''\
-- Written by tib when the entity was created. A change of the schema is a new migration.
CREATE TABLE A (
  ID BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY
);
'''
  }

  def "the SQL creates the sequence of a sequence identifier, the table, and an index for every many-to-one relation"() {
    given:
    Map<String, EntityModel> models = Models.of('''\
      entities:
        - name: B
          id: { strategy: sequence }
        - name: A
          fields:
            - { name: label, type: String, nullable: false }
          relations:
            - { kind: manyToOne, target: B }
            - { kind: oneToOne, target: B, field: other }
            - { kind: manyToOne, target: B, field: third, nullable: false }
      '''.stripIndent())

    expect:
    Migration.sql(models.B) == '''\
CREATE SEQUENCE B_SEQ START WITH 1 INCREMENT BY 50;

CREATE TABLE B (
  ID BIGINT PRIMARY KEY
);
'''
    Migration.sql(models.A) == '''\
CREATE TABLE A (
  ID BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  LABEL VARCHAR(255) NOT NULL,
  B_ID BIGINT REFERENCES B (ID),
  OTHER_ID BIGINT UNIQUE REFERENCES B (ID),
  THIRD_ID BIGINT NOT NULL REFERENCES B (ID)
);

CREATE INDEX A_B_ID_IDX ON A (B_ID);
CREATE INDEX A_THIRD_ID_IDX ON A (THIRD_ID);
'''
  }

  def "the column of the identifier follows its type and its strategy: #id"() {
    expect:
    columns("entities:\n  - name: A\n    id: $id\n") == [column]

    where:
    id                            | column
    '{}'                          | 'ID BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY'
    '{ strategy: sequence }'      | 'ID BIGINT PRIMARY KEY'
    '{ type: UUID, field: code }' | 'CODE UUID PRIMARY KEY'
  }

  def "the column of a field has the SQL type of its type, and the rules of its spec: #field"() {
    expect:
    columns("entities:\n  - name: A\n    fields: [{ name: v, type: $field }]\n")[1] == column

    where:
    field                                               | column
    'String'                                            | 'V VARCHAR(255)'
    'String, length: 20, nullable: false, unique: true' | 'V VARCHAR(20) NOT NULL UNIQUE'
    'Text'                                              | 'V TEXT'
    'Integer, column: QTY, nullable: false'             | 'QTY INTEGER NOT NULL'
    'Long'                                              | 'V BIGINT'
    'BigDecimal'                                        | 'V NUMERIC'
    'BigDecimal, precision: 12, scale: 2'               | 'V NUMERIC(12, 2)'
    'BigDecimal, precision: 12'                         | 'V NUMERIC(12, 0)'
    'Boolean'                                           | 'V BOOLEAN'
    'LocalDate'                                         | 'V DATE'
    'LocalDateTime'                                     | 'V TIMESTAMP'
    'Instant'                                           | 'V TIMESTAMP WITH TIME ZONE'
    'UUID'                                              | 'V UUID'
  }

  def "the column of a relation refers to the identifier of its target, and the audit times come last"() {
    expect:
    columns('''\
      entities:
        - name: B
        - name: C
          id: { type: UUID, field: code }
        - name: A
          audit: true
          relations:
            - { kind: manyToOne, target: B }
            - { kind: oneToOne, target: B, field: other, nullable: false }
            - { kind: manyToOne, target: C }
      '''.stripIndent()) == [
          'ID BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY',
          'B_ID BIGINT REFERENCES B (ID)',
          'OTHER_ID BIGINT NOT NULL UNIQUE REFERENCES B (ID)',
          'C_ID UUID REFERENCES C (CODE)',
          'CREATED_AT TIMESTAMP WITH TIME ZONE NOT NULL',
          'UPDATED_AT TIMESTAMP WITH TIME ZONE NOT NULL'
        ]
  }

  /** The definitions of the columns of the table of the entity A of the spec. */
  private static List<String> columns(String spec) {
    Migration.sql(Models.of(spec).A).readLines().findAll {
      it.startsWith('  ')
    }.collect {
      it.trim().replaceFirst(/,$/, '')
    }
  }

  /** The model of an entity A without fields. */
  private static EntityModel a() {
    Models.of('entities:\n  - name: A\n').A
  }

  /** A migration of the developer's at the path, under the migrations of the service. */
  private void writeMigration(String path) {
    Path file = dir.resolve(Migration.DIRECTORY).resolve(path)
    Files.createDirectories(file.parent)
    Files.writeString(file, '-- mine\n')
  }
}
