package me.yakar.tib.pack;

import java.util.ArrayList;
import java.util.List;
import java.util.Locale;
import java.util.regex.Matcher;
import java.util.regex.Pattern;
import me.yakar.tib.spec.IdStrategy;
import me.yakar.tib.tree.ProjectFiles;

/**
 * The Flyway migration that creates the table of an entity, whatever the stack that reads it: its
 * path among the migrations of the service, and its SQL. A migration lasts: a database may have run
 * it, so it stays when the entity leaves the spec.
 */
public final class Migration {

  /** The directory of the migrations, where Flyway looks for them by default. */
  public static final String DIRECTORY = "src/main/resources/db/migration";

  /**
   * A versioned migration, at any depth: the major part of its version, as in V2__, V2.1__, V2_1__.
   */
  private static final Pattern VERSION = Pattern.compile("/V(\\d+)(?:[._]\\d+)*__");

  private Migration() {}

  /**
   * Stages the migration that creates the table of the entity, as a file that lasts. The pack says
   * by how much the sequence of a sequence identifier advances.
   */
  public static void write(ProjectFiles files, EntityModel entity, int sequenceStep) {
    String path = path(files, entity);
    files.lasting(
        path, Templates.comment(path, Header.MIGRATION.text()) + "\n" + sql(entity, sequenceStep));
  }

  /**
   * The migration that creates the table: the one tib wrote before, there or not, so that a
   * migration the developer removed or renamed stays so; else the one there; else the next major
   * version after the versioned migrations there.
   */
  static String path(ProjectFiles files, EntityModel entity) {
    String suffix = "__create_" + entity.table().toLowerCase(Locale.ROOT) + ".sql";
    for (String migration : files.recorded(DIRECTORY)) {
      if (migration.endsWith(suffix)) {
        return migration;
      }
    }
    long latest = 0;
    for (String migration : files.list(DIRECTORY)) {
      if (migration.endsWith(suffix)) {
        return migration;
      }
      Matcher version = VERSION.matcher(migration);
      if (version.find()) {
        latest = Math.max(latest, Long.parseLong(version.group(1)));
      }
    }
    return DIRECTORY + "/V" + (latest + 1) + suffix;
  }

  /**
   * The SQL of the migration: the sequence of a sequence identifier, the table with its columns,
   * and an index on the column of every many-to-one relation.
   */
  static String sql(EntityModel entity, int sequenceStep) {
    StringBuilder sql = new StringBuilder();
    if (entity.idSequence()) {
      sql.append("CREATE SEQUENCE ")
          .append(entity.sequence())
          .append(" START WITH 1 INCREMENT BY ")
          .append(sequenceStep)
          .append(";\n\n");
    }
    sql.append("CREATE TABLE ").append(entity.table()).append(" (\n");
    sql.append(String.join(",\n", columns(entity).stream().map(column -> "  " + column).toList()));
    sql.append("\n);\n");
    // A one-to-one column is unique, which indexes it.
    List<RelationModel> indexed =
        entity.relations().stream().filter(relation -> !relation.oneToOne()).toList();
    if (!indexed.isEmpty()) {
      sql.append('\n');
      for (RelationModel relation : indexed) {
        sql.append("CREATE INDEX ")
            .append(entity.index(relation))
            .append(" ON ")
            .append(entity.table())
            .append(" (")
            .append(relation.column())
            .append(");\n");
      }
    }
    return sql.toString();
  }

  /** The definitions of the columns of the table. */
  private static List<String> columns(EntityModel entity) {
    List<String> columns = new ArrayList<>();
    columns.add(
        entity.idColumn()
            + " "
            + idType(entity)
            + (entity.idStrategy() == IdStrategy.IDENTITY
                ? " GENERATED BY DEFAULT AS IDENTITY"
                : "")
            + " PRIMARY KEY");
    for (FieldModel field : entity.fields()) {
      columns.add(
          field.column()
              + " "
              + type(field)
              + (field.nullable() ? "" : " NOT NULL")
              + (field.unique() ? " UNIQUE" : ""));
    }
    for (RelationModel relation : entity.relations()) {
      EntityModel target = relation.target();
      columns.add(
          relation.column()
              + " "
              + idType(target)
              + (relation.nullable() ? "" : " NOT NULL")
              + (relation.oneToOne() ? " UNIQUE" : "")
              + " REFERENCES "
              + target.table()
              + " ("
              + target.idColumn()
              + ")");
    }
    if (entity.audited()) {
      columns.add(entity.createdAt() + " TIMESTAMP WITH TIME ZONE NOT NULL");
      columns.add(entity.updatedAt() + " TIMESTAMP WITH TIME ZONE NOT NULL");
    }
    return columns;
  }

  /** The SQL type of the identifier of an entity, and of a column that refers to it. */
  private static String idType(EntityModel entity) {
    return entity.uuidId() ? "UUID" : "BIGINT";
  }

  /** The SQL type of the column of a field. */
  private static String type(FieldModel field) {
    return switch (field.type()) {
      case STRING -> "VARCHAR(" + field.length() + ")";
      case TEXT -> "TEXT";
      case INTEGER -> "INTEGER";
      case LONG -> "BIGINT";
      case BIG_DECIMAL ->
          field.precision() == null
              ? "NUMERIC"
              : "NUMERIC("
                  + field.precision()
                  + ", "
                  + (field.scale() == null ? 0 : field.scale())
                  + ")";
      case BOOLEAN -> "BOOLEAN";
      case LOCAL_DATE -> "DATE";
      case LOCAL_DATE_TIME -> "TIMESTAMP";
      case INSTANT -> "TIMESTAMP WITH TIME ZONE";
      case UUID -> "UUID";
    };
  }
}
